#!/usr/bin/env node
// Regenerates docs/FRAMEWORK.md from the content section of src/qe-health-check.html.
// Usage: node scripts/generate-framework-doc.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "src/qe-health-check.html"), "utf8");
const js = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const content = js.slice(js.indexOf("/* ============ FRAMEWORK CONTENT"), js.indexOf("/* ============ STATE"));
const C = new Function(content + "\nreturn {PILLARS,LEVELS,AILEVELS,EFFORT,OUTCOMES,DIMS,ACTS,TOOLS,READY};")();
const L=[];
L.push('# Assessment framework','','This file is generated from the content section of `src/qe-health-check.html`. Edit the arrays there (`DIMS`, `ACTS`, `READY`, `OUTCOMES`, `TOOLS`) and regenerate; do not edit this file by hand.','');
L.push('## Maturity scale','','| Level | Name |','|---|---|');C.LEVELS.slice(1).forEach((n,i)=>L.push(`| ${i+1} | ${n} |`));
L.push('','AI adoption scale: '+C.AILEVELS.slice(1).map((n,i)=>`${i+1} ${n}`).join(' · '),'');
L.push('## Client outcomes','');C.OUTCOMES.forEach(o=>L.push(`- \`${o.k}\`: ${o.t}`));
L.push('','## QA practice categories','');
let last='';C.DIMS.forEach(d=>{if(d.pillar!==last){last=d.pillar;L.push(`### ${C.PILLARS[d.pillar]}`,'');}
 L.push(`#### ${d.name}`,'',`Linked outcomes: ${d.out.join(', ')}`,'','| Practice | Level 1 | Level 3 | Level 5 | Recommendation | Effort |','|---|---|---|---|---|---|');
 d.qs.forEach(q=>L.push(`| ${q.t} | ${q.a[0]} | ${q.a[1]} | ${q.a[2]} | ${q.rec} | ${C.EFFORT[q.e]} |`));L.push('');});
L.push('## AI across the QA lifecycle','','| Activity | BrainRidge accelerator (sell) | Enablement offer (embed) |','|---|---|---|');
C.ACTS.forEach(a=>L.push(`| ${a.name} | **${a.acc.n}**: ${a.acc.d} | ${a.enb} |`));
L.push('','## AI readiness questions','','| Question | Level 1 | Level 3 | Level 5 |','|---|---|---|---|');C.READY.forEach(r=>L.push(`| ${r.t} | ${r.a.join(' | ')} |`));
L.push('','## Client AI tools and the activities they cover','','| Tool | Activities |','|---|---|');C.TOOLS.forEach(t=>L.push(`| ${t.n} | ${t.acts.map(x=>C.ACTS.find(a=>a.id===x).name).join(', ')} |`));
fs.writeFileSync(path.join(root, "docs/FRAMEWORK.md"), L.join("\n") + "\n");
console.log("Wrote docs/FRAMEWORK.md");
